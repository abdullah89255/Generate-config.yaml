#!/usr/bin/env python3
"""mkconfig.py — generate a h1hunter config.yaml from domain lists.

Reads one or more domain lists, copies them to a stable location, and emits
a config.yaml whose passive_sources point at those copies. The tool then
finds them regardless of where you run it from.

Examples
--------
    # Single list, defaults elsewhere:
    python3 mkconfig.py --program acme --domains-file data/domains.txt

    # Multiple lists:
    python3 mkconfig.py --program acme \
        --list "subdomains:data/subs.txt" \
        --list "curated:data/curated.txt"

    # Disable passive sources entirely:
    python3 mkconfig.py --program acme --no-passive-sources

    # Overwrite an existing config.yaml:
    python3 mkconfig.py --program acme --domains-file data/domains.txt --force

    # Write to a different path:
    python3 mkconfig.py --program acme --domains-file data/domains.txt \
        --output config/acme-config.yaml

Every generated config uses conservative defaults:
    timeout 10s, concurrency 2, 1 req/s, 200-request budget, 512 KB cap.
"""
from __future__ import annotations

import argparse
import shutil
import sys
from datetime import datetime, timezone
from pathlib import Path

# ---------------------------------------------------------------------------


def read_lines(path: Path) -> list[str]:
    if not path.exists():
        raise SystemExit(f"list file not found: {path}")
    if not path.is_file():
        raise SystemExit(f"list path is not a file: {path}")
    out: list[str] = []
    for lineno, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        stripped = line.split("#", 1)[0].strip()
        if stripped:
            out.append(stripped)
    if not out:
        raise SystemExit(f"list file is empty: {path}")
    return out


def slugify(value: str) -> str:
    keep = []
    for ch in value:
        if ch.isalnum() or ch in ("-", "_"):
            keep.append(ch)
        elif ch in (" ", ".", "/", ":"):
            keep.append("-")
    slug = "".join(keep).strip("-").lower()
    return slug or "source"


def parse_list_arg(value: str) -> tuple[str, Path]:
    """Parse ``name:path`` into a tuple. Path may contain colons on Windows."""
    if ":" not in value:
        raise SystemExit(
            f"--list must be 'name:path', got {value!r} (e.g. subdomains:data/subs.txt)"
        )
    name, raw_path = value.split(":", 1)
    name = name.strip()
    raw_path = raw_path.strip()
    if not name or not raw_path:
        raise SystemExit(f"--list must be 'name:path', got {value!r}")
    return slugify(name), Path(raw_path)


# ---------------------------------------------------------------------------


def stage_list(source: Path, staged_dir: Path) -> Path:
    """Copy ``source`` into ``staged_dir`` and return the new path.

    The tool records absolute or relative paths in the config; staging them
    in a known directory keeps the config portable across working directories.
    """
    staged_dir.mkdir(parents=True, exist_ok=True)
    target = staged_dir / source.name
    shutil.copyfile(source, target)
    return target


def build_yaml(
    *,
    program: str,
    staged_lists: list[tuple[str, Path]],
    timeout_seconds: float,
    max_concurrency: int,
    requests_per_second: float,
    max_retries: int,
    max_requests: int,
    max_response_bytes: int,
    output_dir: str,
    user_agent: str,
    log_level: str,
    log_format: str,
    log_file: str | None,
    enabled_modules: list[str],
    disable_passive_sources: bool,
    config_dir: Path,
) -> str:
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d")

    lines: list[str] = []
    lines.append("# h1hunter application configuration")
    lines.append(f"# Generated by mkconfig.py on {now} for program: {program}")
    lines.append("#")
    lines.append("# Copy is unnecessary; this is the working config.")
    lines.append("# Credentials belong in environment variables, never here.")
    lines.append("")

    lines.append(f"timeout_seconds: {timeout_seconds}")
    lines.append(f"max_concurrency: {max_concurrency}")
    lines.append(f"requests_per_second: {requests_per_second}")
    lines.append(f"max_retries: {max_retries}")
    lines.append(f"max_requests: {max_requests}")
    lines.append(f"max_response_bytes: {max_response_bytes}")
    lines.append(f"output_dir: {output_dir}")
    lines.append(f'user_agent: "{user_agent}"')
    lines.append("")

    lines.append("logging:")
    lines.append(f"  level: {log_level}")
    lines.append(f"  format: {log_format}")
    lines.append(f"  file: {('null' if log_file is None else log_file)}")
    lines.append("")

    if enabled_modules:
        lines.append("enabled_modules:")
        for mod in enabled_modules:
            lines.append(f"  - {mod}")
    else:
        lines.append("enabled_modules: []")
    lines.append("")

    if disable_passive_sources or not staged_lists:
        lines.append("passive_sources: []")
    else:
        lines.append("passive_sources:")
        for name, staged in staged_lists:
            lines.append(f"  - name: {name}")
            lines.append("    enabled: true")
            lines.append("    options:")
            lines.append("      type: text")
            # Store paths relative to the project root when possible.
            try:
                rel = staged.relative_to(config_dir.parent.parent)
                path_str = str(rel)
            except ValueError:
                path_str = str(staged)
            lines.append(f"      path: {path_str}")
    lines.append("")
    return "\n".join(lines)


# ---------------------------------------------------------------------------


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    p = argparse.ArgumentParser(
        prog="mkconfig.py",
        description=(
            "Generate a h1hunter config.yaml. Domain lists you supply are "
            "staged under data/ and referenced by the generated file's "
            "passive_sources section."
        ),
    )
    p.add_argument("--program", required=True,
                   help="Program name; used only for the file header.")
    p.add_argument(
        "--domains-file", type=Path, default=None,
        help="A single domain list. Becomes one passive source named 'seed'.",
    )
    p.add_argument(
        "--list", action="append", default=[], metavar="NAME:PATH",
        help="Repeatable. Named list, e.g. --list subdomains:data/subs.txt",
    )
    p.add_argument(
        "--no-passive-sources", action="store_true",
        help="Write an empty passive_sources section.",
    )
    p.add_argument(
        "--output", type=Path, default=Path("config/config.yaml"),
        help="Where to write the config (default: config/config.yaml).",
    )
    p.add_argument(
        "--data-dir", type=Path, default=Path("data"),
        help="Where to stage list copies (default: data/).",
    )
    p.add_argument("--force", action="store_true",
                   help="Overwrite the output file if it exists.")
    p.add_argument(
        "--from-example", action="store_true",
        help="Seed defaults from config/config.example.yaml when it exists.",
    )

    # Conservative defaults; overridable.
    p.add_argument("--timeout-seconds", type=float, default=10.0)
    p.add_argument("--max-concurrency", type=int, default=2)
    p.add_argument("--requests-per-second", type=float, default=1.0)
    p.add_argument("--max-retries", type=int, default=2)
    p.add_argument("--max-requests", type=int, default=200)
    p.add_argument("--max-response-bytes", type=int, default=524288)
    p.add_argument("--output-dir", default="output")
    p.add_argument(
        "--user-agent",
        default="h1hunter/0.4 (+authorized-security-research; contact=you@example.test)",
    )
    p.add_argument("--log-level",
                   choices=("DEBUG", "INFO", "WARNING", "ERROR", "CRITICAL"),
                   default="WARNING")
    p.add_argument("--log-format", choices=("console", "json"), default="console")
    p.add_argument("--log-file", default=None)
    p.add_argument(
        "--enable-module", action="append", default=[], metavar="MOD",
        help="Repeatable. Adds to enabled_modules.",
    )
    return p.parse_args(argv)


# ---------------------------------------------------------------------------


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)

    if args.output.exists() and not args.force:
        print(f"error: {args.output} exists; pass --force to overwrite",
              file=sys.stderr)
        return 2

    # Build the list of (name, source_path) pairs.
    pairs: list[tuple[str, Path]] = []
    if args.domains_file:
        if not args.domains_file.exists():
            print(f"error: --domains-file not found: {args.domains_file}",
                  file=sys.stderr)
            return 2
        read_lines(args.domains_file)  # validate
        pairs.append(("seed", args.domains_file))
    for raw in args.list:
        name, src = parse_list_arg(raw)
        if not src.exists():
            print(f"error: --list source not found: {src}", file=sys.stderr)
            return 2
        read_lines(src)
        pairs.append((name, src))

    if not pairs and not args.no_passive_sources:
        print(
            "warning: no domain lists supplied; passive_sources will be empty",
            file=sys.stderr,
        )

    # Stage lists.
    staged: list[tuple[str, Path]] = []
    for name, src in pairs:
        dst = stage_list(src, args.data_dir)
        staged.append((name, dst))
        print(f"  staged {name}: {src} -> {dst}")

    # Optionally seed from the example.
    if args.from_example:
        example = Path("config/config.example.yaml")
        if example.exists():
            print(f"  (--from-example: {example} present; defaults still applied)")

    text = build_yaml(
        program=args.program,
        staged_lists=staged,
        timeout_seconds=args.timeout_seconds,
        max_concurrency=args.max_concurrency,
        requests_per_second=args.requests_per_second,
        max_retries=args.max_retries,
        max_requests=args.max_requests,
        max_response_bytes=args.max_response_bytes,
        output_dir=args.output_dir,
        user_agent=args.user_agent,
        log_level=args.log_level,
        log_format=args.log_format,
        log_file=args.log_file,
        enabled_modules=list(args.enable_module),
        disable_passive_sources=args.no_passive_sources,
        config_dir=args.output,
    )

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(text, encoding="utf-8")

    print(f"\nWrote {args.output}")
    print(f"  program:            {args.program}")
    print(f"  passive_sources:    {len(staged)}")
    print(f"  timeout_seconds:    {args.timeout_seconds}")
    print(f"  max_concurrency:    {args.max_concurrency}")
    print(f"  requests_per_second:{args.requests_per_second}")
    print(f"  max_requests:       {args.max_requests}")
    print(f"  max_response_bytes: {args.max_response_bytes}")
    print()
    print("Next steps:")
    print(f"  1. Review {args.output}.")
    print(f"  2. Run:  h1hunter recon passive --config {args.output} \\")
    print("              --file config/scope.yaml --output output/passive.json")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
